import importlib.util
import sqlite3
from pathlib import Path

import pytest

from tests.pg import fresh_database_url
from trsm.db import SCHEMA_PATH, get_connection

_SCRIPT = Path(__file__).resolve().parents[1] / "scripts" / "migrate_sqlite_to_postgres.py"
_spec = importlib.util.spec_from_file_location("migrate_sqlite_to_postgres", _SCRIPT)
migration = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(migration)


def _old_sqlite_db(path):
    schema = (
        SCHEMA_PATH.read_text(encoding="utf-8")
        .replace("GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "PRIMARY KEY AUTOINCREMENT")
        .replace("DOUBLE PRECISION", "REAL")
    )
    conn = sqlite3.connect(path)
    conn.executescript(schema)
    # Silinmiş kayıtlar yüzünden id'lerde boşluk olması gerçek veride de görülür.
    conn.execute("INSERT INTO hasta (id, dosya_adi, cinsiyet) VALUES (5, 'Ayşe.pdf', 'Kadın')")
    conn.execute("INSERT INTO hasta (id, dosya_adi) VALUES (9, 'İsmail.pdf')")
    conn.execute(
        """INSERT INTO ziyaret (id, hasta_id, tarih, sayfa_no, ham_mudahale_metni)
           VALUES (3, 9, '2024-01-01', 1, 'Depakin 500 2x1; ğüşıöç')"""
    )
    conn.execute(
        """INSERT INTO ilac_kullanimi (ziyaret_id, ilac_adi_normalize, ilac_adi_ham, eslesme_guveni)
           VALUES (3, 'Depakin', 'Depakin', 85.71428571428571)"""
    )
    conn.execute("INSERT INTO semptom_kaydi (ziyaret_id, ifade_ham, kategori) VALUES (3, 'uykusuzluk', NULL)")
    conn.commit()
    conn.close()


def test_migration_copies_rows_exactly_and_keeps_ids(tmp_path):
    sqlite_path = tmp_path / "eski.db"
    _old_sqlite_db(sqlite_path)
    url = fresh_database_url()

    copied = migration.migrate(sqlite_path, url)

    assert copied["hasta"] == 2 and copied["ziyaret"] == 1 and copied["semptom_kaydi"] == 1
    with get_connection(url) as conn:
        assert conn.execute("SELECT id, dosya_adi FROM hasta ORDER BY id").fetchall() == [
            (5, "Ayşe.pdf"), (9, "İsmail.pdf"),
        ]
        assert conn.execute("SELECT eslesme_guveni FROM ilac_kullanimi").fetchone()[0] == 85.71428571428571
        # Yeni kayıtlar taşınan en büyük id'nin ardından numara almalı.
        new_id = conn.execute("INSERT INTO hasta (dosya_adi) VALUES ('yeni.pdf') RETURNING id").fetchone()[0]
        assert new_id == 10


def test_migration_refuses_to_overwrite_existing_data(tmp_path):
    sqlite_path = tmp_path / "eski.db"
    _old_sqlite_db(sqlite_path)
    url = fresh_database_url()
    migration.migrate(sqlite_path, url)

    with pytest.raises(migration.MigrationError, match="zaten veri var"):
        migration.migrate(sqlite_path, url)

    assert migration.migrate(sqlite_path, url, replace=True)["hasta"] == 2


def test_migration_stops_on_unknown_column_without_writing(tmp_path):
    sqlite_path = tmp_path / "eski.db"
    _old_sqlite_db(sqlite_path)
    with sqlite3.connect(sqlite_path) as conn:
        conn.execute("ALTER TABLE hasta ADD COLUMN beklenmeyen TEXT")
    url = fresh_database_url()

    with pytest.raises(migration.MigrationError, match="beklenmeyen"):
        migration.migrate(sqlite_path, url)

    with get_connection(url) as conn:
        assert conn.execute("SELECT COUNT(*) FROM hasta").fetchone()[0] == 0
